def categorize(text: str) -> str:
    """根据文本中出现的医学术语归类到首个匹配的系统分类；无匹配返回「其他」。

    用于报告主诉归类与图谱节点归属判定。
    """
    if not text:
        return "其他"
    for term in sorted(TERM2CAT, key=len, reverse=True):  # 长词优先，避免「脑卒中」被「脑」截断式误判
        if term in text:
            return TERM2CAT[term]
    return "其他"
