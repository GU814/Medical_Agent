def build_rag_context(citations: list[dict]) -> str:
    """把检索到的片段组装成参考资料块。"""
    if not citations:
        return "【知识库参考资料】（本次未检索到相关内容）"
    lines = ["【知识库参考资料】（回答中引用时须标注来源）"]
    for i, c in enumerate(citations, 1):
        name = c.get("doc_name", "未知文档")
        idx = c.get("chunk_idx", 0) + 1
        text = (c.get("text") or "").strip()[:600]
        lines.append(f"[{i}] 来源：{name}-片段{idx}\n{text}")
    return "\n\n".join(lines)


